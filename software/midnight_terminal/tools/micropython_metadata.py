"""Export palette/font metadata used by the Python scene renderer."""
from pathlib import Path
import re


def export(mp_chars, mk_chars):
    root = Path(__file__).resolve().parents[1]
    c = (root / 'generated/assets.c').read_text(encoding='utf-8')
    arrays = {name: [int(v.strip(), 0) for v in body.split(',') if v.strip()]
              for name, body in re.findall(r'const uint(?:8|16)_t (\w+)\[\d+\]=\{([^}]+)\}', c)}
    for chars, name in ((mp_chars, 'mplus'), (mk_chars, 'misaki')):
        if len(chars) != len(arrays[name + '_adv']):
            raise ValueError('regenerate C font assets before exporting metadata')
    import story
    mp_index, mk_index = ({ch: i for i, ch in enumerate(chars)} for chars in (mp_chars, mk_chars))
    main_strings = [story.SUBTITLE, story.SPEAKER] + [s for _, _, s in story.DIALOGUE]
    main_strings += list(story.CHOICES) + [s for _, s in story.TERMINAL]
    flat = [mp_index[ch] for s in main_strings for ch in s]
    flat += [mk_index[ch] for s in story.LOGS for ch in s]
    flat += [mp_index[ch] for ch in story.MESSAGE]
    if flat != arrays['text_glyphs']:
        raise ValueError('story and checked-in C assets differ; run build_assets.py first')
    lines = ['# Generated by tools/build_assets.py; font order matches assets.c.\n']
    lines.append('CHARS = ' + repr((''.join(mp_chars), ''.join(mk_chars))) + '\n')
    lines.append('ADV = ' + repr(tuple(bytes(arrays[n + '_adv']) for n in ('mplus', 'misaki'))) + '\n')
    lines.append('PALETTES = ' + repr(tuple(tuple(arrays['pal_' + n]) for n in ('title', 'bar', 'terminal', 'bar_red'))) + '\n')
    ascii_source = (root.parent/'fm_megademo/src/font.c').read_text()
    ascii_glyphs = {ch: bytes(int(row.replace('.', '0').replace('#', '1'), 2)
                             for row in re.findall(r'"([.#]{5})"', body))
                    for ch, body in re.findall(r"\{'(.)',\{([^}]+)\}\}", ascii_source)}
    lines.append('ASCII = '+repr(ascii_glyphs)+'\n')
    header = (root / 'generated/assets.h').read_text()
    defs = dict(re.findall(r'^#define (\w+) (\d+)$', header, re.M))
    for key, names in (('SCREEN', ('SCREEN_X0', 'SCREEN_Y0', 'SCREEN_X1', 'SCREEN_Y1')),
                       ('EYE', ('EYE_X', 'EYE_Y', 'EYE_W', 'EYE_H'))):
        lines.append(key + ' = ' + repr(tuple(int(defs[n]) for n in names)) + '\n')
    (root / 'generated/midnight_assets.py').write_text(''.join(lines), encoding='utf-8')


if __name__ == '__main__':
    import story
    main, logs = story.all_text()
    export(sorted(set(main) | set(' ?！？…')), sorted(set(logs) | set(' ')))
