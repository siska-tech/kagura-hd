"""Small procedural painting kit: draw at 2x in linear-ish RGB, then reduce to
640x360 and quantize to a fixed 16-colour RGB444 palette with ordered dither.
All artwork in MIDNIGHT TERMINAL is generated by this code (no external art)."""
from PIL import Image, ImageDraw, ImageFilter
import numpy as np

S = 2                     # supersampling factor
W, H = 640, 360

class Canvas:
    def __init__(self, w=W, h=H):
        self.w, self.h = w, h
        self.rgb = np.zeros((h*S, w*S, 3), np.float32)

    # ------------------------------------------------------------ masks
    def mask(self, draw_fn, blur=0.0):
        """draw_fn(ImageDraw, s) draws in 1x coordinates scaled by s; returns float mask 0..1."""
        im = Image.new('L', (self.w*S, self.h*S), 0)
        draw_fn(ImageDraw.Draw(im), S)
        if blur: im = im.filter(ImageFilter.GaussianBlur(blur*S))
        return np.asarray(im, np.float32)/255.0

    def poly(self, pts, blur=0.0):
        return self.mask(lambda d, s: d.polygon([(x*s, y*s) for x, y in pts], fill=255), blur)

    def ellipse(self, box, blur=0.0):
        x0, y0, x1, y1 = box
        return self.mask(lambda d, s: d.ellipse((x0*s, y0*s, x1*s, y1*s), fill=255), blur)

    def rect(self, box, blur=0.0):
        x0, y0, x1, y1 = box
        return self.mask(lambda d, s: d.rectangle((x0*s, y0*s, x1*s-1, y1*s-1), fill=255), blur)

    def line(self, pts, width, blur=0.0):
        return self.mask(lambda d, s: d.line([(x*s, y*s) for x, y in pts], fill=255, width=max(1, int(width*s)), joint='curve'), blur)

    # ------------------------------------------------------------- paint
    def fill(self, m, color, alpha=1.0):
        c = np.array(color, np.float32)/255.0
        a = (m*alpha)[..., None]
        self.rgb = self.rgb*(1-a)+c*a

    def fill_grad(self, m, top, bottom, y0, y1, alpha=1.0):
        """vertical gradient between y0 and y1 (1x coords) clipped to mask."""
        ys = (np.arange(self.h*S, dtype=np.float32)/S-y0)/max(1e-3, (y1-y0))
        t = np.clip(ys, 0, 1)[:, None, None]
        c = (np.array(top, np.float32)*(1-t)+np.array(bottom, np.float32)*t)/255.0
        a = (m*alpha)[..., None]
        self.rgb = self.rgb*(1-a)+c*a

    def add(self, m, color, gain=1.0):
        """additive light."""
        c = np.array(color, np.float32)/255.0
        self.rgb = self.rgb+(m*gain)[..., None]*c

    def multiply(self, m, color):
        c = np.array(color, np.float32)/255.0
        a = m[..., None]
        self.rgb = self.rgb*(1-a)+self.rgb*c*a

    def radial(self, cx, cy, rx, ry=None, power=2.0):
        ry = ry or rx
        y, x = np.mgrid[0:self.h*S, 0:self.w*S].astype(np.float32)/S
        d = np.sqrt(((x-cx)/rx)**2+((y-cy)/ry)**2)
        return np.clip(1-d, 0, 1)**power

    def cone(self, x, y0, half_top, half_bottom, y1):
        """downward light cone mask with soft edges."""
        yy, xx = np.mgrid[0:self.h*S, 0:self.w*S].astype(np.float32)/S
        t = np.clip((yy-y0)/(y1-y0), 0, 1)
        half = half_top+(half_bottom-half_top)*t
        m = np.clip(1-np.abs(xx-x)/np.maximum(half, 1e-3), 0, 1)**1.5
        return m*(yy >= y0)*(1-t)**0.7

    def snapshot(self):
        return self.rgb.copy()

    # ---------------------------------------------------------- output
    def reduce(self):
        r = self.rgb.reshape(self.h, S, self.w, S, 3).mean(axis=(1, 3))
        return np.clip(r, 0, 1)

BAYER4 = (np.array([[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]], np.float32)+0.5)/16-0.5

def rgb444(hexes):
    out = []
    for h in hexes:
        v = int(h, 16)
        out.append(((v >> 8 & 15)*17, (v >> 4 & 15)*17, (v & 15)*17))
    return np.array(out, np.float32)/255.0

def quantize(img, palette, dither=0.09, protect=None):
    """img HxWx3 0..1, palette Nx3 0..1. Ordered dither in perceptual-ish space.
    protect: optional HxW int array of forced indices (-1 = free)."""
    h, w, _ = img.shape
    th = np.tile(BAYER4, (h//4+1, w//4+1))[:h, :w][..., None]*dither
    x = np.clip(img+th, 0, 1)
    wts = np.array([0.30, 0.59, 0.11], np.float32)*3
    d = (((x[:, :, None, :]-palette[None, None, :, :])**2)*wts).sum(-1)
    idx = d.argmin(-1).astype(np.uint8)
    if protect is not None:
        idx = np.where(protect >= 0, protect, idx).astype(np.uint8)
    return idx

def to_image(idx, palette):
    p = (palette*255).round().astype(np.uint8)
    im = Image.fromarray(idx, 'P')
    flat = list(p.reshape(-1))+[0]*(768-p.size)
    im.putpalette(flat)
    return im

def pack4(idx):
    """640x360 indices -> 115200 bytes, even x in the high nibble."""
    return ((idx[:, 0::2] << 4) | idx[:, 1::2]).astype(np.uint8).tobytes()

def kmeans_palette(img, n=16, locked=(), iters=12, seed=1):
    """Choose an RGB444 palette for img (HxWx3, 0..1). `locked` hex colours stay fixed."""
    rs = np.random.RandomState(seed)
    px = img.reshape(-1, 3)
    sample = px[rs.choice(len(px), min(len(px), 40000), replace=False)]
    fixed = rgb444(locked) if locked else np.zeros((0, 3), np.float32)
    k = n-len(fixed)
    cent = sample[rs.choice(len(sample), k, replace=False)]
    wts = np.array([0.30, 0.59, 0.11], np.float32)*3
    for _ in range(iters):
        allc = np.vstack([fixed, cent])
        d = (((sample[:, None, :]-allc[None])**2)*wts).sum(-1)
        lab = d.argmin(1)
        for j in range(k):
            sel = sample[lab == j+len(fixed)]
            if len(sel): cent[j] = sel.mean(0)
            else: cent[j] = sample[rs.randint(len(sample))]
    cent = np.round(np.clip(cent, 0, 1)*15)/15
    pal = np.vstack([fixed, cent]).astype(np.float32)
    # order by luminance (keep locked first) so indices are stable-ish
    order = list(range(len(fixed)))+sorted(range(len(fixed), n), key=lambda i: (pal[i]*wts).sum())
    return pal[order]

def pal_hex(pal):
    return ['%x%x%x' % tuple(int(round(v*15)) for v in p) for p in pal]
