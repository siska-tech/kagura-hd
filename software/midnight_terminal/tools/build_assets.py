"""Generate src/../generated/assets.c, assets.h, script.h and PNG previews.
usage: python build_assets.py [PREVIEW_DIR]"""
import sys, zlib, json, hashlib
from pathlib import Path
import numpy as np
sys.path.insert(0, str(Path(__file__).parent))
from paint import rgb444, quantize, to_image, pack4, pal_hex
import ai_art, story, fonts, bar_reference

ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT/'generated'; GEN.mkdir(exist_ok=True)
preview = Path(sys.argv[1]) if len(sys.argv) > 1 else None

def deflate(raw):
    c = zlib.compressobj(9, zlib.DEFLATED, -12, 9)
    return c.compress(raw)+c.flush()

def carr(name, data, ctype='uint8_t', per=24):
    vals = list(data)
    body = ',\n'.join(','.join(str(v) for v in vals[i:i+per]) for i in range(0, len(vals), per))
    return f'const {ctype} {name}[{len(vals)}]={{\n{body}\n}};\n'

def pal_words(pal):
    return [int(round(p[0]*15)) << 8 | int(round(p[1]*15)) << 4 | int(round(p[2]*15)) for p in pal]

c_out = ['// Generated by tools/build_assets.py. Do not edit.\n#include "assets.h"\n']
h_out = ['// Generated by tools/build_assets.py. Do not edit.\n#ifndef MT_ASSETS_H\n#define MT_ASSETS_H\n#include <stdint.h>\n']
manifest = {}

# ------------------------------------------------------------------ images
images = {}
bar_idx, bar_pal = bar_reference.bar_indices()
images['bar'] = (bar_idx, bar_pal)
images['title'] = ai_art.title_indices()
images['terminal'] = ai_art.terminal_indices()
for name, (idx, pal) in images.items():
    raw = pack4(idx); z = deflate(raw)
    assert zlib.decompress(z, -12) == raw
    c_out.append(carr(f'img_{name}', z)); c_out.append(carr(f'pal_{name}', pal_words(pal), 'uint16_t', 16))
    h_out.append(f'extern const uint8_t img_{name}[{len(z)}];\nextern const uint16_t pal_{name}[16];\n')
    manifest[name] = dict(deflate_bytes=len(z), sha256_4bpp=hashlib.sha256(raw).hexdigest(), palette=pal_hex(pal))
    if preview:
        preview.mkdir(parents=True, exist_ok=True)
        p = pal.copy()
        if name == 'title': p[12:15] = rgb444(['68a', '9bd', 'cef'])
        to_image(idx, p).resize((1280, 720), 0).save(preview/f'{name}-2x.png')
if preview:
    for name, kw in [('bar-closed', dict(eyes_closed=True)), ('bar-red', dict(anomaly=True))]:
        idx = bar_reference.bar_indices(pal=bar_pal, **kw)[0]
        to_image(idx[100:160, 130:250], bar_pal).resize((960, 480), 0).save(preview/f'{name}-eyes.png')

# Red (anomaly) version of the bar palette: luminance onto a blood-red ramp.
def red_of(pal):
    out = []
    for r, g, b in pal:
        L = 0.30*r+0.59*g+0.11*b
        out.append((min(1, L*1.6), L*0.25, L*0.3))
    return np.array(out, np.float32)
c_out.append(carr('pal_bar_red', pal_words(np.round(red_of(bar_pal)*15)/15), 'uint16_t', 16))
h_out.append('extern const uint16_t pal_bar_red[16];\n')

# Eye patches (same palette as the bar): closed and red.
EYE = bar_reference.EYE_RECT                     # x0 even, x1 even
h_out.append('#define SCREEN_X0 %d\n#define SCREEN_Y0 %d\n#define SCREEN_X1 %d\n#define SCREEN_Y1 %d\n' % ai_art.SCREEN)
h_out.append(f'#define EYE_X {EYE[0]}\n#define EYE_Y {EYE[1]}\n#define EYE_W {EYE[2]-EYE[0]}\n#define EYE_H {EYE[3]-EYE[1]}\n')
for name, kw in [('open', {}), ('closed', dict(eyes_closed=True)), ('red', dict(anomaly=True))]:
    idx = bar_idx if not kw else bar_reference.bar_indices(pal=bar_pal, **kw)[0]
    crop = idx[EYE[1]:EYE[3], EYE[0]:EYE[2]]
    data = ((crop[:, 0::2] << 4) | crop[:, 1::2]).astype(np.uint8).tobytes()
    c_out.append(carr(f'eye_{name}', data)); h_out.append(f'extern const uint8_t eye_{name}[{len(data)}];\n')

# ------------------------------------------------------------------- fonts
(mplus, MH), (misaki, KH) = fonts.load()
main_text, log_text = story.all_text()
mp_chars = sorted(set(main_text) | set(' ?！？…'))
mk_chars = sorted(set(log_text) | set(' '))
def font_table(name, src, chars, height):
    missing = [ch for ch in chars if ord(ch) not in src]
    assert not missing, f'{name}: missing glyphs {missing}'
    index = {ch: i for i, ch in enumerate(chars)}
    rows, adv = [], []
    for ch in chars:
        a, r = src[ord(ch)]; adv.append(a); rows.extend(r)
    c_out.append(carr(f'{name}_adv', adv)); c_out.append(carr(f'{name}_rows', rows, 'uint16_t', 16))
    h_out.append(f'#define {name.upper()}_H {height}\n#define {name.upper()}_GLYPHS {len(chars)}\n'
                 f'extern const uint8_t {name}_adv[{len(chars)}];\nextern const uint16_t {name}_rows[{len(rows)}];\n')
    return index
mp_index = font_table('mplus', mplus, mp_chars, MH)
mk_index = font_table('misaki', misaki, mk_chars, KH)
manifest['fonts'] = dict(mplus=len(mp_chars), misaki=len(mk_chars))

# ------------------------------------------------------------------ script
strings = []                                   # (font, glyph list)
def text_id(s, font='mplus'):
    idx = mp_index if font == 'mplus' else mk_index
    strings.append([idx[ch] for ch in s]); return len(strings)-1
sid = {}
sid['subtitle'] = text_id(story.SUBTITLE); sid['speaker'] = text_id(story.SPEAKER)
dialogue = [(t, text_id(s)) for t, _, s in story.DIALOGUE]
choices = [text_id(s) for s in story.CHOICES]
terminal = [(t, text_id(s)) for t, s in story.TERMINAL]
logs = [text_id(s, 'misaki') for s in story.LOGS]
sid['message'] = text_id(story.MESSAGE)
offs, flat = [], []
for g in strings: offs.append(len(flat)); flat.extend(g)
offs.append(len(flat))
c_out.append(carr('text_glyphs', flat, 'uint16_t', 20)); c_out.append(carr('text_offset', offs, 'uint16_t', 20))
h_out.append(f'extern const uint16_t text_glyphs[{len(flat)}];\nextern const uint16_t text_offset[{len(offs)}];\n')
h_out.append('#endif\n')

s = ['// Generated by tools/build_assets.py from tools/story.py. Do not edit.\n#ifndef MT_SCRIPT_H\n#define MT_SCRIPT_H\n']
def define(k, v): s.append(f'#define {k} {v}\n')
define('CHAR_MS', story.CHAR_MS); define('TERM_CHAR_MS', story.TERM_CHAR_MS)
define('TXT_SUBTITLE', sid['subtitle']); define('TXT_SPEAKER', sid['speaker']); define('TXT_MESSAGE', sid['message'])
define('DIALOGUES', len(dialogue)); define('TERMINAL_LINES', len(terminal)); define('LOG_LINES', len(logs))
s.append('static const struct { uint32_t at; uint16_t text; } DIALOGUE[]={'+','.join(f'{{{t},{i}}}' for t, i in dialogue)+'};\n')
s.append('static const uint16_t CHOICE_TEXT[3]={'+','.join(map(str, choices))+'};\n')
s.append('static const struct { uint32_t at; uint16_t text; } TERMINAL[]={'+','.join(f'{{{t},{i}}}' for t, i in terminal)+'};\n')
s.append('static const uint16_t LOG_TEXT[]={'+','.join(map(str, logs))+'};\n')
for k in ['CHOICE_SHOW', 'CHOICE_PICK', 'GLITCH_START', 'ANOMALY_START', 'ANOMALY_FULL', 'ANOMALY_END', 'MESSAGE_START',
          'MESSAGE_CHAR_MS', 'MESSAGE_END', 'RESTORE_START', 'END_CARD', 'END_MS']:
    define(k, getattr(story, k))
define('CHOICE_MOVE0', story.CHOICE_MOVES[0]); define('CHOICE_MOVE1', story.CHOICE_MOVES[1])
define('RED_EYES_ON', story.RED_EYES[0]); define('RED_EYES_OFF', story.RED_EYES[1])
for name, t in story.SCENES: define('AT_'+name.upper(), t)
s.append('static const char *const END_LINES[]={'+','.join(json.dumps(x) for x in story.END_LINES)+'};\n')
s.append(f'static const char TITLE_TEXT[]={json.dumps(story.TITLE)};\n')
# glyph counts for timing (synth uses them for typing clicks)
s.append('static const uint16_t DIALOGUE_LEN[]={'+','.join(str(len(story.DIALOGUE[i][2])) for i in range(len(dialogue)))+'};\n')
s.append('static const uint16_t TERMINAL_LEN[]={'+','.join(str(len(t)) for _, t in story.TERMINAL)+'};\n')
define('MESSAGE_LEN', len(story.MESSAGE))
s.append('#endif\n')

(GEN/'assets.c').write_text(''.join(c_out), encoding='utf-8')
(GEN/'assets.h').write_text(''.join(h_out), encoding='utf-8')
(GEN/'script.h').write_text(''.join(s), encoding='utf-8')
(GEN/'assets.json').write_text(json.dumps(manifest, indent=2, ensure_ascii=False)+'\n', encoding='utf-8')
print(json.dumps({k: v.get('deflate_bytes', v) if isinstance(v, dict) else v for k, v in manifest.items()}, ensure_ascii=False))
