static uint8_t table[96][FONT_H];

void font_init(void) {
    memset(table,0,sizeof table);
    for (unsigned g=0;g<sizeof SRC/sizeof SRC[0];g++)
        for (unsigned y=0;y<FONT_H;y++) {
            uint8_t bits=0;
            for (unsigned x=0;x<FONT_W;x++) if (SRC[g].rows[y][x]=='#') bits|=(uint8_t)(0x10>>x);
            table[SRC[g].c-32][y]=bits;
        }
}
const uint8_t *font_glyph(char c) {
    if (c>='a' && c<='z') c=(char)(c-32);
    if ((unsigned char)c<32 || (unsigned char)c>127) c='?';
    return table[c-32];
}
unsigned font_width(const char *s, unsigned scale) {
    unsigned n=(unsigned)strlen(s);
    return n ? (n*(FONT_W+1)-1)*scale : 0;
}
